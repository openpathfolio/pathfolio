#!/usr/bin/env node
/**
 * Merge, validate and publish opportunity data.
 *
 *   data/opportunities/curated.json        human-maintained (wins on id conflicts)
 *   data/opportunities/sources/*.json      written by scripts/fetch-opportunities.mjs
 *   → assets/data/opportunities.js         loaded by the web app
 *
 * Usage:  node scripts/build-opportunities.mjs          (write output)
 *         node scripts/build-opportunities.mjs --check  (CI: fail if invalid or out of date)
 * No dependencies; Node 18+.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = join(ROOT, "data/opportunities");
const OUT = join(ROOT, "assets/data/opportunities.js");
const CHECK = process.argv.includes("--check");

const schema = JSON.parse(readFileSync(join(DATA, "schema.json"), "utf8"));
const registry = readFileSync(join(ROOT, "assets/data/common/registry.js"), "utf8");
const AREA_KEYS = new Set([...registry.matchAll(/^\s{2}(\w+):\s*"/gm)].map(m => m[1]));

const errors = [];
function validate(o, where) {
  const props = schema.properties;
  for (const k of schema.required) if (!(k in o)) errors.push(`${where}: missing "${k}"`);
  for (const k of Object.keys(o)) if (!props[k]) errors.push(`${where}: unknown field "${k}"`);
  for (const [k, rule] of Object.entries(props)) {
    if (!(k in o)) continue;
    const v = o[k];
    const types = [].concat(rule.type || []);
    if (rule.enum && !rule.enum.includes(v)) errors.push(`${where}: "${k}" must be one of ${rule.enum.join(", ")}`);
    if (v === null) { if (!types.includes("null")) errors.push(`${where}: "${k}" cannot be null`); continue; }
    if (types.includes("string") && typeof v === "string") {
      if (rule.pattern && !new RegExp(rule.pattern).test(v)) errors.push(`${where}: "${k}" has invalid format`);
      if (rule.minLength && v.length < rule.minLength) errors.push(`${where}: "${k}" too short`);
      if (rule.maxLength && v.length > rule.maxLength) errors.push(`${where}: "${k}" longer than ${rule.maxLength}`);
    } else if (types.includes("array")) {
      if (!Array.isArray(v) || v.length < (rule.minItems || 0)) { errors.push(`${where}: "${k}" must be a non-empty array`); continue; }
      v.forEach(x => {
        if (rule.items.pattern && !new RegExp(rule.items.pattern).test(x)) errors.push(`${where}: "${k}" value "${x}" invalid`);
        if (rule.items.type === "integer" && (!Number.isInteger(x) || x < rule.items.minimum || x > rule.items.maximum)) errors.push(`${where}: "${k}" value "${x}" out of range`);
      });
    } else if (types.includes("boolean") && typeof v !== "boolean") errors.push(`${where}: "${k}" must be true/false`);
    else if (types.includes("integer") && !Number.isInteger(v)) errors.push(`${where}: "${k}" must be an integer`);
  }
  (o.areas || []).forEach(a => { if (!AREA_KEYS.has(a)) errors.push(`${where}: unknown area "${a}"`); });
}

function load(file) {
  try { const arr = JSON.parse(readFileSync(file, "utf8")); if (!Array.isArray(arr)) throw new Error("not an array"); return arr; }
  catch (e) { errors.push(`${file}: ${e.message}`); return []; }
}

const curated = load(join(DATA, "curated.json")).map(o => ({ ...o, source: o.source || "curated" }));
const srcDir = join(DATA, "sources");
const automated = existsSync(srcDir) ? readdirSync(srcDir).filter(f => f.endsWith(".json")).flatMap(f => load(join(srcDir, f))) : [];

const byId = new Map();
for (const o of [...automated, ...curated]) {        // curated last → wins
  validate(o, `${o.source || "?"}:${o.id || "(no id)"}`);
  byId.set(o.id, o);
}
const curatedIds = curated.map(o => o.id);
if (new Set(curatedIds).size !== curatedIds.length) errors.push("curated.json: duplicate ids");

const today = new Date().toISOString().slice(0, 10);
const list = [...byId.values()]
  .filter(o => o.recurring || !o.deadline || o.deadline >= today)   // drop expired one-time listings
  .sort((a, b) => (a.deadline || "9999").localeCompare(b.deadline || "9999") || a.title.localeCompare(b.title));

if (errors.length) { console.error("✖ Opportunity data has problems:\n  " + errors.join("\n  ")); process.exit(1); }

const out = `/* AUTO-GENERATED by scripts/build-opportunities.mjs. Do not edit by hand.
   Edit data/opportunities/curated.json instead. */
const OPPORTUNITIES = ${JSON.stringify(list, null, 1)};
`;
if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== out) { console.error("✖ assets/data/opportunities.js is out of date. Run: node scripts/build-opportunities.mjs"); process.exit(1); }
  console.log(`✓ ${list.length} opportunities valid and up to date`);
} else {
  writeFileSync(OUT, out);
  console.log(`✓ Wrote ${list.length} opportunities (${curated.length} curated, ${automated.length} automated)`);
}
