#!/usr/bin/env node
/**
 * Check every external link in the site data and write a Markdown report.
 *
 *   node scripts/check-links.mjs [--out report.md] [--concurrency 6] [--timeout 15000]
 *
 * Exit code: always 0 (the workflow decides what to do from the report header),
 * unless --strict is passed, in which case broken links → exit 1.
 * Writes "<!-- broken:N blocked:M ok:K -->" as the first line of the report.
 * No dependencies; Node 18+.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > -1 ? process.argv[i + 1] : d; };
const OUT = arg("out", null);
const CONCURRENCY = +arg("concurrency", 6);
const TIMEOUT = +arg("timeout", 15000);
const STRICT = process.argv.includes("--strict");
const UA = "PathfolioLinkCheck/1.0 (+https://github.com/openpathfolio/pathfolio)";

const SKIP = [/youtube\.com\/results/, /\/\/example\.(org|com|edu)\b/, /^https:\/\/github\.com\/openpathfolio\/pathfolio\/(issues|compare|pull)/];

function walk(dir, exts, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, exts, out);
    else if (exts.some(e => f.endsWith(e))) out.push(p);
  }
  return out;
}
const files = [join(ROOT, "index.html"), ...walk(join(ROOT, "assets/data"), [".js"]), ...walk(join(ROOT, "data"), [".json"])]
  .filter(f => !f.endsWith("schema.json"));

/* url → Set(files) */
const urls = new Map();
for (const f of files) {
  const text = readFileSync(f, "utf8");
  for (const m of text.matchAll(/https:\/\/[^\s"'`<>)\]\\]+/g)) {
    const u = m[0].replace(/[.,;:]+$/, "");
    if (u.includes("${") || SKIP.some(r => r.test(u))) continue;
    if (!urls.has(u)) urls.set(u, new Set());
    urls.get(u).add(relative(ROOT, f));
  }
}

async function probe(url, method) {
  const ctrl = new AbortController(); const t = setTimeout(() => ctrl.abort(), TIMEOUT);
  try {
    const res = await fetch(url, { method, redirect: "follow", signal: ctrl.signal, headers: { "User-Agent": UA, "Accept": "text/html,*/*" } });
    if (method === "GET") res.body?.cancel().catch(() => {});
    return { status: res.status };
  } catch (e) { return { status: 0, error: e.name === "AbortError" ? "timeout" : (e.cause?.code || e.message) }; }
  finally { clearTimeout(t); }
}
async function check(url) {
  let r = await probe(url, "HEAD");
  if (r.status === 0 || r.status === 405 || r.status === 403 || r.status === 404 || r.status >= 500) r = await probe(url, "GET"); // many servers mishandle HEAD
  if (r.status === 0 || r.status >= 500) { await new Promise(s => setTimeout(s, 1500)); r = await probe(url, "GET"); } // one retry
  /* blocked = the site refused or ignored an automated check (bot protection, rate limits, timeouts);
     broken  = a definite failure: 404/410, server error, unknown domain, bad TLS certificate */
  const kind = r.status >= 200 && r.status < 400 ? "ok"
    : [401, 403, 429, 999].includes(r.status) || r.error === "timeout" ? "blocked" : "broken";
  return { url, ...r, kind };
}

const list = [...urls.keys()];
const results = [];
let next = 0;
await Promise.all(Array.from({ length: Math.min(CONCURRENCY, list.length) }, async () => {
  while (next < list.length) { const u = list[next++]; results.push(await check(u)); }
}));
results.sort((a, b) => a.url.localeCompare(b.url));

const broken = results.filter(r => r.kind === "broken"), blocked = results.filter(r => r.kind === "blocked");
const ok = results.length - broken.length - blocked.length;
const row = r => `| ${r.url} | ${r.status || r.error} | ${[...urls.get(r.url)].map(f => "`" + f + "`").join(", ")} |`;
const md = [
  `<!-- broken:${broken.length} blocked:${blocked.length} ok:${ok} -->`,
  `## 🔗 Link check: ${new Date().toISOString().slice(0, 10)}`,
  `Checked **${results.length}** unique links in ${files.length} files: **${broken.length} broken**, ${blocked.length} need a manual check, ${ok} OK.`,
  broken.length ? "\n### ❌ Broken (please fix or replace)\n| URL | Status | Found in |\n|---|---|---|\n" + broken.map(row).join("\n") : "\n✅ No broken links.",
  blocked.length ? "\n<details><summary>🔒 " + blocked.length + " site(s) refused or timed out on the automated check (often bot protection): open them manually</summary>\n\n| URL | Status | Found in |\n|---|---|---|\n" + blocked.map(row).join("\n") + "\n</details>" : "",
  "\n<sub>Generated by `scripts/check-links.mjs` · YouTube search links are skipped.</sub>"
].join("\n");

if (OUT) writeFileSync(OUT, md + "\n"); else console.log(md);
console.error(`✓ ${results.length} links: ${broken.length} broken, ${blocked.length} blocked, ${ok} ok`);
if (STRICT && broken.length) process.exit(1);
